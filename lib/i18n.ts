export function eventHappenedLabel(
  lang: Lang,
  type: string,
  stage?: string | null,
  resultingStatus?: string | null,
  previousStatus?: string | null,
): string {
  if (type === "status_change") {
    const typeText = eventTypeLabel(lang, type);
    if (previousStatus && resultingStatus) {
      const change = `\u2066${statusLabel(lang, previousStatus)} → ${statusLabel(lang, resultingStatus)}\u2069`;
      return `${typeText} (${change})`;
    }
    return resultingStatus ? `${typeText} (${statusLabel(lang, resultingStatus)})` : typeText;
  }
  if (type !== "meeting") return eventTypeLabel(lang, type);
  const stageText = stage ? stageLabel(lang, stage) : "";
  if (lang === "he") return stageText ? `פגישת ${stageText} נקבעה` : "פגישה נקבעה";
  return stageText ? `${stageText} meeting scheduled` : "Meeting scheduled";
}

export function meetingKindLabel(lang: Lang, stage?: string | null): string {
  const stageText = stage ? stageLabel(lang, stage) : "";
  if (lang === "he") return stageText ? `ראיון ${stageText}` : "ראיון";
  return stageText ? `${stageText} interview` : "Interview";
}

